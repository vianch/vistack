import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";

import { hookBlock } from "./token-guard.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const script = join(here, "token-guard.mjs");
const scratch = realpathSync(mkdtempSync(join(tmpdir(), "token-guard-install-test-")));
after(() => rmSync(scratch, { recursive: true, force: true }));

// git runs only in fresh repositories under the scratch directory, with global and system config
// shut out so a global core.hooksPath cannot redirect an install.
const emptyConfig = join(scratch, "empty.gitconfig");
writeFileSync(emptyConfig, "");
const isolated = { ...process.env, GIT_CONFIG_GLOBAL: emptyConfig, GIT_CONFIG_NOSYSTEM: "1", GIT_CEILING_DIRECTORIES: scratch };
delete isolated.TOKEN_GUARD_LIMIT;

const header = "// @generated by token-guard install; do not edit, run install again to update";
const copyOf = (file) => `${header}\n${readFileSync(join(here, file), "utf8")}`;
const run = (args, cwd) => spawnSync(process.execPath, [script, ...args], { cwd, env: isolated, encoding: "utf8" });
const gitIn = (cwd, ...args) => {
  const result = spawnSync("git", args, { cwd, env: isolated, encoding: "utf8" });
  assert.equal(result.status, 0, `git ${args.join(" ")}: ${result.stderr}`);
};
let made = 0;
const makeRepo = (label) => {
  const root = join(scratch, `${label}-${(made += 1)}`);
  mkdirSync(root, { recursive: true });
  gitIn(root, "init", "-q");
  gitIn(root, "config", "user.email", "test@example.com");
  gitIn(root, "config", "user.name", "Test");
  gitIn(root, "config", "commit.gpgsign", "false");
  return root;
};
const put = (root, path, content) => {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
};
const read = (root, path) => readFileSync(join(root, path), "utf8");

describe("install and uninstall", () => {
  test("without .husky: writes both copies and the block once, and the copied hook blocks a commit", () => {
    const root = makeRepo("install-plain");
    const first = run(["install"], root);
    assert.equal(first.status, 0, first.stderr);
    assert.match(first.stdout, /\.git\/hooks\/token-guard\.mjs: copied/);
    assert.match(first.stdout, /\.git\/hooks\/split-plan\.mjs: copied/);
    assert.match(first.stdout, /\.git\/hooks\/pre-commit: token-guard block created/);
    assert.match(first.stdout, /To uninstall: /);
    for (const file of ["token-guard.mjs", "split-plan.mjs"]) {
      assert.equal(read(root, `.git/hooks/${file}`), copyOf(file), `${file}: the copy is the generated header line plus the source`);
    }
    assert.equal(read(root, ".git/hooks/pre-commit"), `#!/bin/sh\n${hookBlock()}\n`);
    assert.ok(statSync(join(root, ".git/hooks/pre-commit")).mode & 0o111, "the hook is executable");

    const second = run(["install"], root);
    assert.equal(second.status, 0);
    assert.match(second.stdout, /unchanged \(same bytes\)/);
    assert.match(second.stdout, /already has the token-guard block; nothing changed/);
    assert.equal(read(root, ".git/hooks/pre-commit").split("# >>> token-guard").length, 2);

    put(root, "big.txt", "x".repeat(24000));
    gitIn(root, "add", "big.txt");
    const blocked = spawnSync("git", ["commit", "-q", "-m", "big"], { cwd: root, env: isolated, encoding: "utf8" });
    assert.notEqual(blocked.status, 0);
    assert.match(blocked.stderr, /token-guard: 1 staged file over 5,000 tokens/);
    assert.match(blocked.stderr, /How to split \(Other\):/, "the copy imported split-plan.mjs from beside the hook");

    const removed = run(["uninstall"], root);
    assert.equal(removed.status, 0, removed.stderr);
    assert.ok(!existsSync(join(root, ".git/hooks/pre-commit")), "a hook that held only the block is removed");
    assert.ok(!existsSync(join(root, ".git/hooks/token-guard.mjs")));
    assert.ok(!existsSync(join(root, ".git/hooks/split-plan.mjs")));
    assert.match(run(["uninstall"], root).stdout, /nothing to remove/);
    gitIn(root, "commit", "-q", "-m", "big");
  });

  test("an existing hook gets the block appended, and uninstall restores it byte for byte", () => {
    const root = makeRepo("install-existing");
    const original = "#!/bin/sh\necho existing check\n";
    writeFileSync(join(root, ".git/hooks/pre-commit"), original, { mode: 0o644 });
    const result = run(["install", "--limit", "8000"], root);
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /token-guard block appended/);
    assert.equal(read(root, ".git/hooks/pre-commit"), `${original}${hookBlock(8000)}\n`);
    assert.match(read(root, ".git/hooks/pre-commit"), /token-guard\.mjs" check --limit 8000\n# <<< token-guard\n$/);
    assert.ok(statSync(join(root, ".git/hooks/pre-commit")).mode & 0o111, "chmod runs on append too");
    run(["uninstall"], root);
    assert.equal(read(root, ".git/hooks/pre-commit"), original);
  });

  test("with .husky: copies both files into .husky, the install commit is not blocked by them, and uninstall restores", () => {
    const root = makeRepo("install-husky");
    const original = "npx lint-staged\n";
    put(root, ".husky/pre-commit", original);
    const first = run(["install"], root);
    assert.equal(first.status, 0, first.stderr);
    assert.match(first.stdout, /\.husky\/token-guard\.mjs: copied/);
    assert.match(first.stdout, /\.husky\/split-plan\.mjs: copied/);
    assert.match(first.stdout, /Commit \.husky\/pre-commit, \.husky\/token-guard\.mjs, and \.husky\/split-plan\.mjs/);
    assert.equal(read(root, ".husky/pre-commit"), `${original}${hookBlock()}\n`);
    assert.ok(!existsSync(join(root, ".git/hooks/pre-commit")), "nothing is written to .git/hooks");

    gitIn(root, "add", ".husky");
    const installCommit = run(["check", "--json"], root);
    assert.equal(installCommit.status, 0, "the commit that adds the copies is not blocked by them");
    const skipped = JSON.parse(installCommit.stdout).skipped.sort((left, right) => left.path.localeCompare(right.path));
    assert.deepEqual(skipped, [
      { path: ".husky/split-plan.mjs", reason: "generated header" },
      { path: ".husky/token-guard.mjs", reason: "generated header" },
    ]);

    writeFileSync(join(root, ".husky/token-guard.mjs"), "// stale copy\n");
    const second = run(["install"], root);
    assert.match(second.stdout, /\.husky\/token-guard\.mjs: updated/);
    assert.match(second.stdout, /\.husky\/split-plan\.mjs: unchanged \(same bytes\)/);
    assert.match(second.stdout, /nothing changed/);
    assert.equal(read(root, ".husky/token-guard.mjs"), copyOf("token-guard.mjs"));

    run(["uninstall"], root);
    assert.equal(read(root, ".husky/pre-commit"), original);
    assert.ok(!existsSync(join(root, ".husky/token-guard.mjs")));
    assert.ok(!existsSync(join(root, ".husky/split-plan.mjs")));
  });

  test("with lefthook.yml or .pre-commit-config.yaml and no .husky: prints the entry and writes nothing", () => {
    for (const manager of ["lefthook.yml", ".pre-commit-config.yaml"]) {
      const root = makeRepo("install-manager");
      put(root, manager, "# config\n");
      const result = run(["install", "--limit", "6000"], root);
      assert.equal(result.status, 0, result.stderr);
      assert.ok(result.stdout.includes(`found ${manager}; wrote nothing`), result.stdout);
      const copyCommand = `for file in token-guard.mjs split-plan.mjs; do { echo '${header}'; cat "${here}/$file"; } > "scripts/$file"; done`;
      assert.ok(result.stdout.includes(copyCommand), result.stdout);
      assert.match(result.stdout, /node scripts\/token-guard\.mjs check --limit 6000/);
      assert.ok(!existsSync(join(root, ".git/hooks/pre-commit")));
      assert.ok(!existsSync(join(root, "scripts")));
    }
  });
});
