// token-guard: files over a token limit (tokens = ceil(bytes / 4)) fail. `install` copies this file
// and split-plan.mjs beside the pre-commit hook, which runs outside the host, so both import only
// Node. Exit codes: 0 pass or done, 1 bad input, 2 a file over the limit, 3 no git or no repository.

import { chmodSync, existsSync, lstatSync, mkdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, extname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { analyze, commas } from "./split-plan.mjs";

export { analyze };

const self = fileURLToPath(import.meta.url);
const name = "token-guard.mjs";
const copies = [name, "split-plan.mjs"];
const usage = `usage: node token-guard.mjs [check] [--limit <n>] [--json] [--files <path>...]
       node token-guard.mjs explain <path> [--limit <n>]
       node token-guard.mjs install [--limit <n>]
       node token-guard.mjs uninstall`;
const begin = "# >>> token-guard (keeps staged files under the token limit; remove this block to uninstall)";
const end = "# <<< token-guard";
const header = "// @generated by token-guard install; do not edit, run install again to update";
const managers = ["lefthook.yml", ".pre-commit-config.yaml"];
const set = (text) => new Set(text.split(" "));
const lockfiles = set("package-lock.json npm-shrinkwrap.json yarn.lock pnpm-lock.yaml bun.lock bun.lockb Cargo.lock poetry.lock uv.lock Pipfile.lock Gemfile.lock composer.lock go.sum flake.lock Podfile.lock pubspec.lock mix.lock packages.lock.json gradle.lockfile");
const generatedDirectories = set("node_modules vendor dist build .next coverage __generated__ generated __snapshots__");
const generatedName = /\.(generated|gen)\.|\.pb\.(go|ts)$|_pb2(_grpc)?\.py$|\.min\.(js|css)$|\.(map|snap|lock)$/;
const binaryExtensions = set("png jpg jpeg gif webp avif ico bmp tiff svgz pdf woff woff2 ttf otf eot mp3 mp4 webm mov wav ogg zip gz tgz bz2 xz 7z jar wasm so dylib dll exe bin ipa apk");
const generatedHeader = /@generated|DO NOT EDIT|AUTO-GENERATED|Code generated by|automatically generated/i;
const attributeReasons = { "linguist-generated true": "linguist-generated", "linguist-generated set": "linguist-generated", "token-guard ignore": "token-guard=ignore", "token-guard unset": "-token-guard" };

export class TokenGuardError extends Error {
  constructor(message, code = 1) {
    super(message);
    this.code = code;
  }
}

const fail = (message, code) => {
  throw new TokenGuardError(message, code);
};

export const countTokens = (buffer) => Math.ceil(buffer.length / 4);
const parseLimit = (text, source) => (/^[1-9]\d*$/.test(text) ? Number(text) : fail(`${source} must be a positive whole number of tokens, got ${JSON.stringify(text)}`));
export const resolveLimit = (flag, environment) =>
  flag !== undefined ? parseLimit(String(flag), "--limit") : environment ? parseLimit(environment, "TOKEN_GUARD_LIMIT") : 5000;

export const pathSkipReason = (path, mode) => {
  const parts = path.split("/");
  const file = parts.pop();
  if (mode === "120000") return "symlink";
  if (mode === "160000") return "submodule";
  if (lockfiles.has(file) || file.endsWith(".lock")) return "lockfile";
  if (parts.some((part) => generatedDirectories.has(part)) || generatedName.test(file)) return "generated path";
  return binaryExtensions.has(extname(file).slice(1).toLowerCase()) ? "binary extension" : null;
};

export const contentSkipReason = (buffer) => {
  if (buffer.subarray(0, 8000).includes(0)) return "binary content";
  return generatedHeader.test(buffer.subarray(0, 65536).toString().split("\n", 10).join("\n")) ? "generated header" : null;
};

export const parseAttributes = (output) => {
  const fields = String(output).split("\0");
  const reasons = new Map();
  for (let index = 0; index + 2 < fields.length; index += 3) {
    const reason = attributeReasons[`${fields[index + 1]} ${fields[index + 2]}`];
    if (reason && !reasons.has(fields[index])) reasons.set(fields[index], reason);
  }
  return reasons;
};

// ":<old mode> <new mode> <old sha> <new sha> <status>", then one path, or two for a rename.
export const parseRawDiff = (output) => {
  const fields = String(output).split("\0");
  const entries = [];
  for (let index = 0; index < fields.length; index += 1) {
    if (!fields[index].startsWith(":")) continue;
    const [, mode, , , status = ""] = fields[index].split(" ");
    index += /^[RC]/.test(status) ? 2 : 1;
    if (fields[index]) entries.push({ path: fields[index], mode });
  }
  return entries;
};


// attributes() is asked only about files over the limit.
export const checkEntries = ({ entries, limit, read, attributes }) => {
  const skipped = [];
  const measured = [];
  for (const entry of entries) {
    let reason = entry.skip ?? pathSkipReason(entry.match ?? entry.path, entry.mode);
    const buffer = reason ? null : read(entry);
    reason ??= contentSkipReason(buffer);
    if (reason) skipped.push({ path: entry.path, reason });
    else measured.push({ entry, buffer, tokens: countTokens(buffer) });
  }
  const large = measured.filter((item) => item.tokens > limit);
  const marked = large.length ? attributes(large.map((item) => item.entry)) : new Map();
  const over = [];
  for (const { entry, buffer, tokens } of large) {
    const reason = marked.get(entry.path);
    if (reason) skipped.push({ path: entry.path, reason });
    else over.push({ path: entry.path, bytes: buffer.length, tokens, over: tokens - limit, ...analyze(entry.path, buffer) });
  }
  return { limit, checked: measured.length - large.length + over.length, skipped, over };
};

const describeItem = (item, distance) => [
  `${item.path}: ${commas(item.tokens)} tokens (${commas(item.bytes)} bytes; ${distance})`,
  `  How to split (${item.kind}):`,
  ...item.suggestions.map((line) => `    - ${line}`),
];

export const formatMessage = ({ report, staged }) => {
  const count = report.over.length;
  const steps = [
    ...(staged ? ["unstage while you split: git restore --staged <path>", "split as above, run the tests, then git add the new files and the shrunken original"] : ["split as above, run the tests, and keep each new file under the limit"]),
    "a generated or data file is exempt once .gitattributes marks it: echo '<path> token-guard=ignore' >> .gitattributes",
    "the limit is per repository: TOKEN_GUARD_LIMIT=8000, or --limit 8000 on the hook line, agreed with the team first",
  ];
  return [
    `token-guard: ${count} ${staged ? "staged " : ""}file${count === 1 ? "" : "s"} over ${commas(report.limit)} tokens (tokens = bytes / 4)`,
    "",
    ...report.over.flatMap((item) => describeItem(item, `${commas(item.over)} over`).map((line) => `  ${line}`)),
    "",
    "Then:",
    ...steps.map((step, index) => `  ${index + 1}. ${step}`),
    ...(staged ? ["Do not bypass the hook; split the file or mark it as data."] : []),
  ].join("\n");
};

const git = (args, cwd, input) => {
  const result = spawnSync("git", args, { cwd, input, maxBuffer: Infinity });
  if (result.error) fail(`cannot run git: ${result.error.code ?? result.error.message}`, 3);
  if (result.status) fail(args[0] === "rev-parse" ? `not inside a git work tree (${cwd}); run this in the consuming repository` : `git ${args[0]} failed: ${result.stderr}`, 3);
  return result.stdout;
};

const repositoryRoot = (cwd) => String(git(["rev-parse", "--show-toplevel"], cwd)).trim();
const readAttributes = (root, paths) => (paths.length ? parseAttributes(git(["check-attr", "--stdin", "-z", "linguist-generated", "token-guard"], root, `${paths.join("\0")}\0`)) : new Map());

const checkStaged = (cwd, limit) => {
  const root = repositoryRoot(cwd);
  return checkEntries({
    entries: parseRawDiff(git(["diff", "--cached", "--raw", "-z", "--no-abbrev", "--no-renames", "--diff-filter=ACMR"], root)),
    limit,
    // ":0:" names stage 0, so a path that itself starts with "<digit>:" stays a path.
    read: (entry) => git(["show", `:0:${entry.path}`], root),
    attributes: (entries) => readAttributes(root, entries.map((entry) => entry.path)),
  });
};

const outside = (path) => !path || path.startsWith("../") || isAbsolute(path);
const statPath = (cwd, path) => {
  const absolute = resolve(cwd, path);
  return { absolute, stats: lstatSync(absolute, { throwIfNoEntry: false }) ?? fail(`no such file: ${path}`) };
};

// .gitattributes is read only when the cwd is inside a repository.
const checkWorktree = (cwd, limit, files) =>
  checkEntries({
    entries: files.map((path) => {
      const { absolute, stats } = statPath(cwd, path);
      const near = relative(cwd, absolute);
      return { path, absolute, skip: stats.isSymbolicLink() ? "symlink" : stats.isDirectory() ? "directory" : undefined, match: outside(near) ? path : near };
    }),
    limit,
    read: (entry) => readFileSync(entry.absolute),
    attributes: (large) => {
      let root;
      try {
        root = realpathSync(repositoryRoot(cwd));
      } catch {
        return new Map();
      }
      const inside = large.map((entry) => ({ path: entry.path, key: relative(root, realpathSync(entry.absolute)) })).filter((entry) => !outside(entry.key));
      const reasons = readAttributes(root, inside.map((entry) => entry.key));
      return new Map(inside.map((entry) => [entry.path, reasons.get(entry.key)]));
    },
  });

const explain = (cwd, path, limit) => {
  const { absolute, stats } = statPath(cwd, path);
  if (stats.isDirectory()) fail(`${path} is a directory; explain takes one file`);
  const buffer = readFileSync(absolute);
  const tokens = countTokens(buffer);
  const distance = `${commas(Math.abs(tokens - limit))} ${tokens > limit ? "over" : "under"} the ${commas(limit)} limit`;
  const [first, ...rest] = describeItem({ path, tokens, bytes: buffer.length, ...analyze(path, buffer) }, distance);
  return [`token-guard: ${first}`, ...rest];
};

export const hookBlock = (limit) => [begin, `node "$(dirname "$0")/${name}" check${limit ? ` --limit ${limit}` : ""}`, end].join("\n");

const replaceBlock = (content, block) => {
  const lines = content.split("\n");
  const start = lines.findIndex((line) => line.startsWith("# >>> token-guard"));
  const stop = lines.findIndex((line, index) => start >= 0 && index > start && line.startsWith(end));
  return stop < 0 ? null : [...lines.slice(0, start), ...(block ? [block] : []), ...lines.slice(stop + 1)];
};

export const addBlock = (content, block) => {
  if (content === null) return { content: `#!/bin/sh\n${block}\n`, change: "created" };
  const lines = replaceBlock(content, block);
  if (!lines) return { content: `${content}${content && !content.endsWith("\n") ? "\n" : ""}${block}\n`, change: "appended" };
  return { content: lines.join("\n"), change: lines.join("\n") === content ? "unchanged" : "updated" };
};

// "" when only a shebang would remain, null when the block is absent.
export const removeBlock = (content) => {
  const kept = replaceBlock(content, "");
  return kept && (kept.some((line, index) => line.trim() && !(index === 0 && line.startsWith("#!"))) ? kept.join("\n") : "");
};

const hooksDirectory = (root) => resolve(root, String(git(["rev-parse", "--git-path", "hooks"], root)).trim());

// Each copy is a generated header line plus the source, so the header rule skips a committed copy.
// Installing from a copy strips its header first.
const headed = (file) => {
  const text = readFileSync(join(dirname(self), file), "utf8");
  return `${header}\n${text.startsWith(`${header}\n`) ? text.slice(header.length + 1) : text}`;
};

const writeHook = (root, directory, limit) => {
  const hook = join(directory, "pre-commit");
  const where = relative(root, hook);
  const copied = copies.map((file) => relative(root, join(directory, file)));
  mkdirSync(directory, { recursive: true });
  const lines = copies.map((file, index) => {
    const [copy, expected] = [join(directory, file), headed(file)];
    const had = existsSync(copy);
    const same = had && readFileSync(copy, "utf8") === expected;
    if (!same) writeFileSync(copy, expected);
    return `token-guard: ${copied[index]}: ${same ? "unchanged (same bytes)" : had ? "updated" : "copied"}`;
  });
  const { content, change } = addBlock(existsSync(hook) ? readFileSync(hook, "utf8") : null, hookBlock(limit));
  if (change !== "unchanged") writeFileSync(hook, content);
  chmodSync(hook, 0o755);
  return [
    ...lines,
    `token-guard: ${where}: ${change === "unchanged" ? "already has the token-guard block; nothing changed" : `token-guard block ${change}`}`,
    `To uninstall: node ${copied[0]} uninstall, or delete the lines from "# >>> token-guard" to "${end}" in ${where} and delete ${copied.join(" and ")}.`,
    ...(relative(root, directory) === ".husky" ? [`Commit ${where}, ${copied.join(", and ")} so the hook runs for every clone.`] : []),
  ];
};

const snippet = (manager, limit) => {
  const run = `node scripts/${name} check${limit ? ` --limit ${limit}` : ""}`;
  const lefthook = manager === managers[0];
  const entry = lefthook
    ? `pre-commit:\n  commands:\n    token-guard:\n      run: ${run}`
    : `- repo: local\n  hooks:\n    - id: token-guard\n      name: token-guard\n      entry: ${run}\n      language: system\n      pass_filenames: false`;
  return [
    `token-guard: found ${manager}; wrote nothing. Add the hook through it:`,
    `  1. mkdir -p scripts && for file in ${copies.join(" ")}; do { echo '${header}'; cat "${dirname(self)}/$file"; } > "scripts/$file"; done`,
    `  2. add to ${manager}${lefthook ? "" : ", under repos:"}`,
    ...entry.split("\n").map((line) => `     ${line}`),
    `To uninstall: remove that entry, scripts/${copies[0]}, and scripts/${copies[1]}.`,
  ];
};

const install = (cwd, limit) => {
  const root = repositoryRoot(cwd);
  const husky = join(root, ".husky");
  if (statSync(husky, { throwIfNoEntry: false })?.isDirectory()) return writeHook(root, husky, limit);
  const manager = managers.find((file) => existsSync(join(root, file)));
  return manager ? snippet(manager, limit) : writeHook(root, hooksDirectory(root), limit);
};

const uninstall = (cwd) => {
  const root = repositoryRoot(cwd);
  const lines = [];
  for (const directory of new Set([join(root, ".husky"), hooksDirectory(root)])) {
    const hook = join(directory, "pre-commit");
    const rest = existsSync(hook) ? removeBlock(readFileSync(hook, "utf8")) : null;
    if (rest) writeFileSync(hook, rest);
    else if (rest === "") rmSync(hook);
    if (rest !== null) lines.push(`token-guard: ${relative(root, hook)}: ${rest ? "token-guard block removed" : "deleted"}`);
    for (const copy of copies.map((file) => join(directory, file)).filter((path) => existsSync(path))) {
      rmSync(copy);
      lines.push(`token-guard: ${relative(root, copy)}: deleted`);
    }
  }
  return lines.length ? lines : ["token-guard: no token-guard block or copied script found; nothing to remove"];
};

export const parseArgs = (argv) => {
  const more = (prefix = "-") => argv.length > 0 && !argv[0].startsWith(prefix);
  const command = more() ? argv.shift() : "check";
  const bad = (text) => fail(`${text}\n${usage}`);
  if (!["check", "explain", "install", "uninstall"].includes(command)) bad(`unknown command ${command}`);
  const options = { command, json: false, help: false, paths: [] };
  while (argv.length) {
    const flag = argv.shift();
    if (flag === "--help" || flag === "-h") options.help = true;
    else if (flag === "--json" && command === "check") options.json = true;
    else if (flag === "--limit" && command !== "uninstall") options.limit = more() ? parseLimit(argv.shift(), "--limit") : bad("--limit needs a number");
    else if (flag === "--files" && command === "check") {
      options.files = [];
      while (more("--")) options.files.push(argv.shift());
    } else if (command === "explain" && !flag.startsWith("-")) options.paths.push(flag);
    else bad(`unexpected argument ${flag}`);
  }
  if (options.files?.length === 0) bad("--files needs at least one path");
  if (!options.help && command === "explain" && options.paths.length !== 1) bad("explain takes exactly one path");
  return options;
};

const main = () => {
  try {
    const { command, files, help, json, limit: flag, paths } = parseArgs(process.argv.slice(2));
    const cwd = process.cwd();
    const limit = () => resolveLimit(flag, process.env.TOKEN_GUARD_LIMIT);
    if (help) return console.log(usage);
    if (command === "install") return console.log(install(cwd, flag).join("\n"));
    if (command === "uninstall") return console.log(uninstall(cwd).join("\n"));
    if (command === "explain") return console.log(explain(cwd, paths[0], limit()).join("\n"));
    const report = files ? checkWorktree(cwd, limit(), files) : checkStaged(cwd, limit());
    if (json) console.log(JSON.stringify(report, null, 2));
    if (report.over.length) {
      console.error(formatMessage({ report, staged: !files }));
      process.exitCode = 2;
    }
  } catch (error) {
    console.error(`token-guard: ${error.message}`);
    process.exitCode = error instanceof TokenGuardError ? error.code : 1;
  }
};

if (process.argv[1] && realpathSync(process.argv[1]) === self) main();
