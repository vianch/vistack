import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";

import {
  addBlock,
  analyze,
  contentSkipReason,
  countTokens,
  formatMessage,
  hookBlock,
  parseArgs,
  parseAttributes,
  parseRawDiff,
  pathSkipReason,
  removeBlock,
  resolveLimit,
  TokenGuardError,
} from "./token-guard.mjs";

const script = join(dirname(fileURLToPath(import.meta.url)), "token-guard.mjs");
const scratch = realpathSync(mkdtempSync(join(tmpdir(), "token-guard-test-")));
after(() => rmSync(scratch, { recursive: true, force: true }));

// git runs only in fresh repositories under the scratch directory, with global and system config
// shut out so the machine's settings cannot change the result.
const emptyConfig = join(scratch, "empty.gitconfig");
writeFileSync(emptyConfig, "");
const isolated = { ...process.env, GIT_CONFIG_GLOBAL: emptyConfig, GIT_CONFIG_NOSYSTEM: "1", GIT_CEILING_DIRECTORIES: scratch };
delete isolated.TOKEN_GUARD_LIMIT;

const run = (args, { cwd, env = {} } = {}) => spawnSync(process.execPath, [script, ...args], { cwd, env: { ...isolated, ...env }, encoding: "utf8" });
const gitIn = (cwd, ...args) => {
  const result = spawnSync("git", args, { cwd, env: isolated, encoding: "utf8" });
  assert.equal(result.status, 0, `git ${args.join(" ")}: ${result.stderr}`);
};
let made = 0;
const makeDirectory = (label) => {
  const path = join(scratch, `${label}-${(made += 1)}`);
  mkdirSync(path, { recursive: true });
  return path;
};
const makeRepo = (label) => {
  const root = makeDirectory(label);
  gitIn(root, "init", "-q");
  return root;
};
const put = (root, path, content) => {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
};
const big = (tokens = 6000) => "filler line to grow the file past the limit\n".repeat(Math.ceil((tokens * 4) / 44));
const json = (result) => JSON.parse(result.stdout);

const editorSource = [
  'import React from "react";',
  "",
  "export type EditorProps = { value: string };",
  "const MaxRows = 40;",
  "const clamp = (value: number) => Math.min(value, MaxRows);",
  "",
  "export const EditorToolbar = () => <div>toolbar</div>;",
  "export const EditorPane = ({ value }: EditorProps) => <pre>{value.slice(0, clamp(value.length))}</pre>;",
  "",
  ...Array.from({ length: 420 }, (_, index) => `// note ${index}: padding that pushes this component file past the limit`),
  "",
].join("\n");

describe("tokens", () => {
  test("tokens are bytes / 4 rounded up, counted on the Buffer", () => {
    assert.deepEqual([0, 1, 4, 5, 87610].map((length) => countTokens(Buffer.alloc(length))), [0, 1, 1, 2, 21903]);
    const accented = Buffer.from("\u00e9\u00e9\u00e9", "utf8");
    assert.equal(accented.length, 6);
    assert.equal(countTokens(accented), 2);
  });

  test("the limit comes from --limit, then TOKEN_GUARD_LIMIT, then 5000", () => {
    assert.equal(resolveLimit(undefined, undefined), 5000);
    assert.equal(resolveLimit(undefined, "8000"), 8000);
    assert.equal(resolveLimit("7000", "8000"), 7000);
    assert.throws(() => resolveLimit(undefined, "lots"), (error) => error instanceof TokenGuardError && error.code === 1);
  });
});

describe("ignore rules", () => {
  test("path rules run in order: symlink, submodule, lockfile, generated path, binary extension", () => {
    const cases = {
      "src/link.ts 120000": "symlink",
      "vendored 160000": "submodule",
      "dist/yarn.lock 100644": "lockfile",
      "deps/custom.lock 100644": "lockfile",
      "web/go.sum 100644": "lockfile",
      "app/node_modules/x/index.js 100644": "generated path",
      "api/types.generated.ts 100644": "generated path",
      "proto/user_pb2.py 100644": "generated path",
      "public/app.min.js 100644": "generated path",
      "img/Logo.PNG 100644": "binary extension",
      "scripts/build 100755": null,
      "src/Editor.tsx 100644": null,
    };
    for (const [input, reason] of Object.entries(cases)) assert.equal(pathSkipReason(...input.split(" ")), reason, input);
  });

  test("content rules: a NUL byte in the first 8,000 bytes, then a generated header in the first 10 lines", () => {
    assert.equal(contentSkipReason(Buffer.from("abc\0def")), "binary content");
    assert.equal(contentSkipReason(Buffer.concat([Buffer.alloc(9000, 97), Buffer.from([0])])), null);
    assert.equal(contentSkipReason(Buffer.from("// Code generated by protoc. DO NOT EDIT.\nconst a = 1;\n")), "generated header");
    assert.equal(contentSkipReason(Buffer.from("# This file is automatically generated\n")), "generated header");
    assert.equal(contentSkipReason(Buffer.from(`${"line\n".repeat(10)}// @generated\n`)), null);
  });

  test("the plugin's own scripts carry no generated header, so they are measured like any authored file", () => {
    for (const file of [script, join(dirname(script), "split-plan.mjs")]) assert.equal(contentSkipReason(readFileSync(file)), null, file);
  });

  test("check-attr output maps linguist-generated and both token-guard forms to reasons", () => {
    const rows = [["a", "true", "unspecified"], ["b", "set", "unspecified"], ["c", "unspecified", "ignore"], ["d", "false", "unset"], ["e", "unspecified", "unspecified"]];
    const output = `${rows.flatMap(([path, generated, guard]) => [path, "linguist-generated", generated, path, "token-guard", guard]).join("\0")}\0`;
    assert.deepEqual([...parseAttributes(output)], [["a", "linguist-generated"], ["b", "linguist-generated"], ["c", "token-guard=ignore"], ["d", "-token-guard"]]);
  });

  test("each rule skips a staged file in a real repository, and the rest are measured", () => {
    const root = makeRepo("ignore");
    for (const path of ["yarn.lock", "pkg/dist/bundle.js", "assets/logo.png", "src/fixtures.ts", "src/table.ts", "src/seed.ts", "src/real.ts"]) put(root, path, big());
    put(root, "data/blob.txt", `head\0${big()}`);
    put(root, "src/schema.ts", `// Code generated by protoc-gen-ts. DO NOT EDIT.\n${big()}`);
    put(root, "src/small.ts", "export const small = 1;\n");
    put(root, ".gitattributes", "src/fixtures.ts linguist-generated\nsrc/table.ts token-guard=ignore\nsrc/seed.ts -token-guard\n");
    symlinkSync("src/real.ts", join(root, "link.ts"));
    gitIn(root, "add", "-A");
    gitIn(root, "update-index", "--add", "--cacheinfo", `160000,${"a".repeat(40)},vendored`);

    const result = run(["check", "--json"], { cwd: root });
    assert.equal(result.status, 2, result.stderr);
    const report = json(result);
    assert.deepEqual(Object.fromEntries(report.skipped.map(({ path, reason }) => [path, reason])), {
      "assets/logo.png": "binary extension",
      "data/blob.txt": "binary content",
      "link.ts": "symlink",
      "pkg/dist/bundle.js": "generated path",
      "src/fixtures.ts": "linguist-generated",
      "src/schema.ts": "generated header",
      "src/seed.ts": "-token-guard",
      "src/table.ts": "token-guard=ignore",
      vendored: "submodule",
      "yarn.lock": "lockfile",
    });
    assert.deepEqual(report.over.map(({ path }) => path), ["src/real.ts"]);
    assert.equal(report.checked, 3, "src/real.ts, src/small.ts, and .gitattributes are measured");
  });
});

describe("staged and worktree copies", () => {
  test("check reads the index copy; check --files reads the worktree copy", () => {
    const root = makeRepo("staged");
    put(root, "notes.md", "## Small\n\nshort\n");
    gitIn(root, "add", "notes.md");
    put(root, "notes.md", `## Grown\n\n${big()}`);
    const staged = run(["check"], { cwd: root });
    assert.equal(staged.status, 0, staged.stderr);
    assert.equal(staged.stdout + staged.stderr, "", "a pass prints nothing");
    const worktree = run(["check", "--files", "notes.md"], { cwd: root });
    assert.equal(worktree.status, 2);
    assert.match(worktree.stderr, /^token-guard: 1 file over 5,000 tokens/);
    assert.match(worktree.stderr, /notes\.md: 6,0\d\d tokens/);
  });

  test("--files works outside a repository, where .gitattributes is not read", () => {
    const directory = makeDirectory("plain");
    put(directory, "big.txt", big());
    put(directory, ".gitattributes", "big.txt token-guard=ignore\n");
    const result = run(["check", "--files", "big.txt", "--json"], { cwd: directory });
    assert.equal(result.status, 2, result.stderr);
    assert.deepEqual(json(result).over.map(({ path }) => path), ["big.txt"]);
  });

  test("--files honors .gitattributes inside a repository and skips directories", () => {
    const root = makeRepo("files-attr");
    put(root, "data/rows.json", big());
    put(root, ".gitattributes", "data/rows.json token-guard=ignore\n");
    const result = run(["check", "--files", "data/rows.json", "data", "--json"], { cwd: root });
    assert.equal(result.status, 0, result.stderr);
    assert.deepEqual(json(result).skipped, [{ path: "data", reason: "directory" }, { path: "data/rows.json", reason: "token-guard=ignore" }]);
  });
});

describe("exit codes", () => {
  test("0 when nothing is over the limit", () => {
    const root = makeRepo("exit0");
    put(root, "a.ts", "export const a = 1;\n");
    gitIn(root, "add", "a.ts");
    assert.equal(run(["check"], { cwd: root }).status, 0);
    assert.equal(run([], { cwd: root }).status, 0, "check is the default command");
  });

  test("1 for an unknown command, an unknown flag, a bad limit, or a missing path", () => {
    const directory = makeDirectory("exit1");
    for (const args of [["frobnicate"], ["check", "--bogus"], ["check", "--limit", "zero"], ["check", "--files"], ["check", "--files", "missing.ts"], ["explain"], ["explain", "missing.md"]]) {
      const result = run(args, { cwd: directory });
      assert.equal(result.status, 1, `${args.join(" ")}: ${result.stderr}`);
      assert.match(result.stderr, /^token-guard: /);
    }
    assert.equal(run(["check"], { cwd: directory, env: { TOKEN_GUARD_LIMIT: "-5" } }).status, 1);
  });

  test("2 when a file is over the limit; the flag and the variable move the line, and the limit itself passes", () => {
    const root = makeRepo("exit2");
    const stage = (content) => {
      put(root, "big.txt", content);
      gitIn(root, "add", "big.txt");
    };
    stage(big(6000));
    assert.equal(run(["check"], { cwd: root }).status, 2);
    assert.equal(run(["check", "--limit", "8000"], { cwd: root }).status, 0);
    assert.equal(run(["check"], { cwd: root, env: { TOKEN_GUARD_LIMIT: "8000" } }).status, 0);
    assert.equal(run(["check", "--limit", "5000"], { cwd: root, env: { TOKEN_GUARD_LIMIT: "8000" } }).status, 2);
    stage("a".repeat(20000));
    assert.equal(run(["check"], { cwd: root }).status, 0, "exactly 5,000 tokens is at the limit, not over it");
    stage("a".repeat(20001));
    assert.equal(run(["check"], { cwd: root }).status, 2);
  });

  test("3 outside a repository or without git, when the command needs one", () => {
    const directory = makeDirectory("exit3");
    for (const args of [["check"], ["install"], ["uninstall"]]) {
      const result = run(args, { cwd: directory });
      assert.equal(result.status, 3, `${args.join(" ")}: ${result.stderr}`);
      assert.match(result.stderr, /not inside a git work tree/);
    }
    const noGit = run(["check"], { cwd: directory, env: { PATH: makeDirectory("empty-path") } });
    assert.equal(noGit.status, 3);
    assert.match(noGit.stderr, /cannot run git/);
  });
});

describe("output", () => {
  test("--json prints the report shape on stdout and the message on stderr", () => {
    const root = makeRepo("json");
    put(root, "src/Editor.tsx", editorSource);
    put(root, "package-lock.json", "{}\n");
    gitIn(root, "add", "-A");
    const result = run(["check", "--json"], { cwd: root });
    assert.equal(result.status, 2);
    const report = json(result);
    assert.deepEqual(Object.keys(report), ["limit", "checked", "skipped", "over"]);
    assert.deepEqual([report.limit, report.checked, report.skipped], [5000, 1, [{ path: "package-lock.json", reason: "lockfile" }]]);
    const [item] = report.over;
    assert.deepEqual(Object.keys(item), ["path", "bytes", "tokens", "over", "kind", "suggestions"]);
    assert.deepEqual([item.path, item.bytes, item.kind], ["src/Editor.tsx", Buffer.byteLength(editorSource), "TypeScript/React"]);
    assert.deepEqual([item.tokens, item.over], [Math.ceil(item.bytes / 4), Math.ceil(item.bytes / 4) - 5000]);
    assert.ok(Array.isArray(item.suggestions) && item.suggestions.length > 0);
    assert.match(result.stderr, /^token-guard: 1 staged file over 5,000 tokens/);
  });

  test("the message names the file, its tokens, the limit, and how to split two exported components", () => {
    const root = makeRepo("message");
    put(root, "src/Editor.tsx", editorSource);
    gitIn(root, "add", "-A");
    const result = run(["check"], { cwd: root });
    assert.equal(result.status, 2);
    assert.equal(result.stdout, "");
    const message = result.stderr;
    const tokens = Math.ceil(Buffer.byteLength(editorSource) / 4).toLocaleString("en-US");
    assert.match(message, /^token-guard: 1 staged file over 5,000 tokens \(tokens = bytes \/ 4\)\n\n/);
    assert.ok(message.includes(`  src/Editor.tsx: ${tokens} tokens (`), message);
    for (const expected of [
      /How to split \(TypeScript\/React\):/,
      /exported declarations \(2\): EditorToolbar, EditorPane\. Keep one component per file/,
      /types and interfaces \(1\) go to types\/editor\.d\.ts: EditorProps/,
      /non-exported helpers \(1\) go to lib\/utils\/editor\.utils\.ts: clamp/,
      /constants \(1\) go to lib\/constants\/editor\.constants\.ts: MaxRows/,
      /src\/Editor\.tsx stays as the file that imports and composes the pieces/,
      /1\. unstage while you split: git restore --staged <path>/,
      /echo '<path> token-guard=ignore' >> \.gitattributes/,
    ]) {
      assert.match(message, expected);
    }
    assert.ok(!message.includes("--no-verify"), "the message never offers the bypass flag");
  });

  test("no message for any kind mentions the bypass flag", () => {
    const over = [["a.tsx", editorSource], ["b.md", "## A\n\ntext\n"], ["c.json", '{"a": 1}'], ["d.txt", "x\n"]].map(([path, text]) => ({ path, bytes: 1, tokens: 1, over: 1, ...analyze(path, text) }));
    for (const staged of [true, false]) assert.ok(!formatMessage({ report: { limit: 5000, over }, staged }).includes("--no-verify"));
  });

  test("analysis covers tests, Python, Markdown, JSON, YAML, and other files", () => {
    const tests = analyze("src/cart.test.ts", 'describe("totals", () => {\n  test("adds", () => {});\n});\ndescribe("discounts", () => {});\n');
    assert.equal(tests.kind, "TypeScript tests");
    assert.match(tests.suggestions[0], /^describe blocks \(2\) by size: "totals" \d+ tokens, "discounts" \d+ tokens$/);
    assert.match(tests.suggestions[1], /cart\.totals\.test\.ts for "totals"/);

    const python = analyze("engine.py", "class Engine:\n    pass\n\ndef run():\n    pass\n");
    assert.equal(python.kind, "Python");
    assert.match(python.suggestions[0], /^top-level definitions \(2\) by size: class Engine \d+ tokens, def run \d+ tokens$/);
    assert.match(python.suggestions[1], /engine\/__init__\.py re-exporting/);

    const skill = analyze("skills/x/SKILL.md", "# x\n\n## Steps\n\n1. one\n\n```\n## not a heading\n```\n\n## Gotchas\n\n- g\n");
    assert.equal(skill.kind, "Markdown");
    assert.match(skill.suggestions[0], /^H2 sections \(2\) by size: "## Steps" \d+ tokens, "## Gotchas" \d+ tokens$/);
    assert.match(skill.suggestions[2], /SKILL\.md should stay under 500 lines/);

    const data = analyze("config.json", JSON.stringify({ routes: [1, 2, 3], theme: { a: 1 } }));
    assert.equal(data.kind, "JSON");
    assert.match(data.suggestions[0], /^top-level keys \(2\) by size: "routes"/);
    const yaml = analyze("ci.yml", "jobs:\n  build: {}\non: push\n");
    assert.equal(yaml.kind, "YAML");
    assert.match(yaml.suggestions[0], /^top-level keys \(2\) by size/);

    const other = analyze("notes.txt", "one\ntwo\nthree\n");
    assert.equal(other.kind, "Other");
    assert.match(other.suggestions[0], /^3 lines; split by responsibility/);
  });

  test("explain on a Markdown file lists H2 sections by size, largest first", () => {
    const directory = makeDirectory("explain");
    put(directory, "guide.md", `# Guide\n\n## Small\n\n${"a".repeat(400)}\n\n## Large\n\n${"b".repeat(4000)}\n`);
    const result = run(["explain", "guide.md"], { cwd: directory });
    assert.equal(result.status, 0, result.stderr);
    assert.match(result.stdout, /^token-guard: guide\.md: 1,1\d\d tokens \(4,4\d\d bytes; 3,8\d\d under the 5,000 limit\)/);
    assert.match(result.stdout, /How to split \(Markdown\):/);
    assert.match(result.stdout, /H2 sections \(2\) by size: "## Large" 1,0\d\d tokens, "## Small" 10\d tokens/);
    assert.match(result.stdout, /starting with "## Large" as references\/large\.md/);
  });
});

describe("helpers", () => {
  test("raw diff parsing keeps the index mode and the new path of a rename", () => {
    const output = [":000000 100644 0 1 A", "src/a.ts", ":100644 120000 1 2 M", "link", ":100644 100644 1 2 R087", "old.ts", "new.ts", ""].join("\0");
    assert.deepEqual(parseRawDiff(output), [
      { path: "src/a.ts", mode: "100644" },
      { path: "link", mode: "120000" },
      { path: "new.ts", mode: "100644" },
    ]);
  });

  test("the block is added once, replaced when the limit changes, and removed cleanly", () => {
    const created = addBlock(null, hookBlock());
    assert.equal(created.change, "created");
    assert.equal(addBlock(created.content, hookBlock()).change, "unchanged");
    const updated = addBlock(created.content, hookBlock(9000));
    assert.equal(updated.change, "updated");
    assert.match(updated.content, /check --limit 9000/);
    assert.equal(removeBlock(created.content), "");
    assert.equal(removeBlock("echo hi\n"), null);
    const appended = addBlock("echo hi", hookBlock());
    assert.equal(appended.change, "appended");
    assert.equal(removeBlock(appended.content), "echo hi\n");
  });

  test("arguments: check is the default, --files collects paths until the next flag", () => {
    assert.deepEqual(parseArgs([]), { command: "check", json: false, help: false, paths: [] });
    const parsed = parseArgs(["--files", "a.ts", "b.ts", "--json", "--limit", "7000"]);
    assert.deepEqual([parsed.command, parsed.files, parsed.json, parsed.limit], ["check", ["a.ts", "b.ts"], true, 7000]);
    assert.throws(() => parseArgs(["uninstall", "--limit", "5"]), /unexpected argument --limit/);
    assert.throws(() => parseArgs(["install", "--json"]), /unexpected argument --json/);
  });
});
